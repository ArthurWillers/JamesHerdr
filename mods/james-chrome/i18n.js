export function supportedLangs() {
  return SUPPORTED_LANGS;
}

export function currentLang() {
  return "en";
}

let published = false;
export function publishI18n() {
  if (published && shared("james.i18n.dict")) return;
  published = true;
  setShared("james.i18n.lang", "en");
  setShared("james.i18n.langs", SUPPORTED_LANGS);
  setShared("james.i18n.dict", EN);
}

export function tr(key, vars = null) {
  let text = EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v ?? ""));
    }
  }
  return text;
}
