const DICT = {
  en: EN,
  "pt-BR": PT_BR,
  pt: PT_BR,
  "es-MX": ES,
  es: ES,
  fr: FR,
  de: DE,
  it: IT,
  ja: JA,
  ko: KO,
  "zh-CN": ZH_CN,
  "zh-TW": ZH_TW,
  zh: ZH_CN,
  ru: RU,
  vi: VI,
};

export function resolveLang(raw) {
  const code = String(raw || "en").trim().split(".")[0].replaceAll("_", "-");
  if (DICT[code]) return code;
  if (SUPPORTED_LANGS.some((l) => l.code === code)) return code;
  const base = code.split("-")[0].toLowerCase();
  if (DICT[base]) return base;
  return "en";
}

export function currentLang() {
  const mode = shared("james.langMode") ?? "auto";
  if (mode !== "auto") return resolveLang(mode);
  return resolveLang(shared("james.lang") ?? "en");
}

export function tr(key, vars = null) {
  const lang = currentLang();
  let text = DICT[lang]?.[key] ?? EN[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v ?? ""));
    }
  }
  return text;
}
